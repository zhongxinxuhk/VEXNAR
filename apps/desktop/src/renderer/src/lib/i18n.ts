export type MessageKey = keyof (typeof messages)['zh']

function readLocale(): Locale {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh'
  } catch {
    return 'zh'
  }
}

type I18nState = {
  locale: Locale
  setLocale: (locale: Locale) => void
  toggleLocale: () => void
}

export const useI18n = create<I18nState>((set, get) => ({
  locale: readLocale(),
  setLocale: (locale) => {
    try {
      localStorage.setItem(STORAGE_KEY, locale)
    } catch {
      // Language still works for the current session.
    }
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
    set({ locale })
  },
  toggleLocale: () => get().setLocale(get().locale === 'zh' ? 'en' : 'zh')
}))

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const value = messages[locale][key] ?? messages.zh[key] ?? key
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? `{${name}}`))
}

export function useT(): (key: MessageKey, vars?: Record<string, string | number>) => string {
  const locale = useI18n((state) => state.locale)
  return useCallback(
    (key, vars) => translate(locale, key, vars),
    [locale]
  )
}
