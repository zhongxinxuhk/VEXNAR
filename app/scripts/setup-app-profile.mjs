/**
 * Prepare the local dsh web profile used by the GoLand run configuration.
 *
 * Steps:
 *   1. resolve the dsh runtime (packaged app by default);
 *   2. install app/vexnar/ui into $DSH_HOME/profiles/web via `dsh plugin`;
 *   3. write the profile patch: VEXNAR provider + MCP endpoint + UI row.
 *
 * Re-runnable: the plugin install is idempotent (pnpm), and the patch file is
 * regenerated from app/vexnar/cordis.patch.yml.
 */
import { spawnSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { dshHome, resolveRuntime } from './dsh-runtime.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..', '..')
const runtime = resolveRuntime()
const home = dshHome()
const profile = join(home, 'profiles', 'web')
const bin = join(runtime, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js')
const ui = join(repo, 'app', 'vexnar', 'ui')

await mkdir(profile, { recursive: true })

const install = spawnSync(
  process.execPath,
  [bin, 'plugin', '--profile', 'web', 'add', `file:${ui}`],
  { env: { ...process.env, DSH_HOME: home }, stdio: 'inherit' }
)
if (install.status !== 0) process.exit(install.status ?? 1)

const bundlePatch = await readFile(join(repo, 'app', 'vexnar', 'cordis.patch.yml'), 'utf8')
const uiRow = [
  '# Generated by app/scripts/setup-app-profile.mjs — edit app/vexnar/cordis.patch.yml instead.',
  '',
  '- insert:',
  '    - id: vexnar-ui',
  "      name: '@vexnar/dsh-ui'",
  '',
  bundlePatch.trim(),
  ''
].join('\n')
await writeFile(join(profile, 'cordis.patch.yml'), uiRow)
console.log(`[app] profile ready: ${join(profile, 'cordis.patch.yml')}`)
